#!/usr/bin/env node
/**
 * Build-time ZIP bundler for Cloudflare Workers deployment.
 *
 * Packs `packages/extension/` and `figma-plugin/` into `src/generated/bundles.ts`
 * so `@charkle/worker` can serve `/api/v1/extension/download` and
 * `/api/v1/figma-plugin/download` with ZERO runtime filesystem (`node:fs`) access.
 */

import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import JSZip from 'jszip';

const FIXED_ZIP_DATE = new Date('2025-01-01T00:00:00.000Z');

const EXCLUDED_DIRS = new Set(['tests', 'test', '__tests__', 'node_modules']);
const EXCLUDED_EXTENSION_FILES = new Set([
  '.DS_Store',
  'Thumbs.db',
  'package.json',
  'package-lock.json',
  'tsconfig.json',
]);
const EXCLUDED_FIGMA_FILES = new Set(['.DS_Store', 'Thumbs.db', 'ui-template.html']);

function isExcludedExtensionFile(name) {
  if (name.startsWith('.')) return true;
  if (EXCLUDED_EXTENSION_FILES.has(name)) return true;
  if (/^vitest\.config\./i.test(name)) return true;
  if (/\.(?:test|spec)\.[^.]+$/i.test(name)) return true;
  if (/\.map$/i.test(name)) return true;
  return false;
}

function isExcludedFigmaFile(name) {
  if (name.startsWith('.')) return true;
  if (EXCLUDED_FIGMA_FILES.has(name)) return true;
  return false;
}

async function collectFiles(rootDir, isExcludedFile, subDir = '') {
  const currentDir = subDir ? path.join(rootDir, subDir) : rootDir;
  const entries = await fsp.readdir(currentDir, { withFileTypes: true });
  entries.sort((a, b) => a.name.localeCompare(b.name));

  const files = [];
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (entry.name.startsWith('.') || EXCLUDED_DIRS.has(entry.name)) {
        continue;
      }
      const nextSub = subDir ? `${subDir}/${entry.name}` : entry.name;
      files.push(...(await collectFiles(rootDir, isExcludedFile, nextSub)));
    } else if (entry.isFile()) {
      if (isExcludedFile(entry.name)) continue;
      files.push({
        absPath: path.join(currentDir, entry.name),
        relPath: subDir ? `${subDir}/${entry.name}` : entry.name,
      });
    }
  }
  return files;
}

async function zipDirectory(rootDir, isExcludedFile) {
  if (!fs.existsSync(path.join(rootDir, 'manifest.json'))) {
    return { base64: '', fileCount: 0, byteLength: 0, files: [] };
  }

  const files = await collectFiles(rootDir, isExcludedFile);
  if (files.length === 0) {
    return { base64: '', fileCount: 0, byteLength: 0, files: [] };
  }

  const zip = new JSZip();
  for (const file of files) {
    const data = await fsp.readFile(file.absPath);
    zip.file(file.relPath, data, { date: FIXED_ZIP_DATE });
  }

  const bytes = await zip.generateAsync({
    type: 'uint8array',
    compression: 'DEFLATE',
    compressionOptions: { level: 6 },
  });

  return {
    base64: Buffer.from(bytes).toString('base64'),
    fileCount: files.length,
    byteLength: bytes.byteLength,
    files: files.map((f) => f.relPath),
  };
}

async function main() {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const workerDir = path.resolve(here, '..');
  const repoRoot = path.resolve(workerDir, '../..');

  const extensionDir = path.join(repoRoot, 'packages', 'extension');
  const figmaPluginDir = path.join(repoRoot, 'figma-plugin');
  const outDir = path.join(workerDir, 'src', 'generated');
  const outFile = path.join(outDir, 'bundles.ts');

  const [extBundle, figmaBundle] = await Promise.all([
    zipDirectory(extensionDir, isExcludedExtensionFile),
    zipDirectory(figmaPluginDir, isExcludedFigmaFile),
  ]);

  if (extBundle.fileCount === 0) {
    throw new Error(`No extension files found in ${extensionDir}`);
  }
  if (figmaBundle.fileCount === 0) {
    throw new Error(`No Figma plugin files found in ${figmaPluginDir}`);
  }

  const generatedSource = `// AUTO-GENERATED by packages/worker/scripts/pack-zips.mjs — DO NOT EDIT.
// Regenerate with \`npm run cf:pack\` (or \`npm run pack-zips -w @charkle/worker\`).

import type { IBundleAssets } from '@charkle/server/worker';

const EXTENSION_ZIP_BASE64 = ${JSON.stringify(extBundle.base64)};
const FIGMA_PLUGIN_ZIP_BASE64 = ${JSON.stringify(figmaBundle.base64)};

export const BUNDLE_METADATA = {
  extension: {
    fileCount: ${extBundle.fileCount},
    byteLength: ${extBundle.byteLength},
  },
  figmaPlugin: {
    fileCount: ${figmaBundle.fileCount},
    byteLength: ${figmaBundle.byteLength},
  },
} as const;

function decodeBase64ToBytes(b64: string): Uint8Array {
  if (!b64) return new Uint8Array(0);
  const binary = atob(b64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) {
    bytes[i] = binary.charCodeAt(i);
  }
  return bytes;
}

let cachedExtensionZip: Uint8Array | null = null;
let cachedFigmaPluginZip: Uint8Array | null = null;

/**
 * Returns a Cloudflare Workers-safe \`IBundleAssets\` backed by build-time
 * embedded ZIP archives (zero \`node:fs\` calls at runtime).
 */
export function createBundledAssets(): IBundleAssets {
  return {
    async getExtensionZip(): Promise<Uint8Array | null> {
      if (!EXTENSION_ZIP_BASE64) return null;
      if (!cachedExtensionZip) {
        cachedExtensionZip = decodeBase64ToBytes(EXTENSION_ZIP_BASE64);
      }
      return cachedExtensionZip.slice();
    },

    async getFigmaPluginZip(): Promise<Uint8Array | null> {
      if (!FIGMA_PLUGIN_ZIP_BASE64) return null;
      if (!cachedFigmaPluginZip) {
        cachedFigmaPluginZip = decodeBase64ToBytes(FIGMA_PLUGIN_ZIP_BASE64);
      }
      return cachedFigmaPluginZip.slice();
    },
  };
}
`;

  await fsp.mkdir(outDir, { recursive: true });
  let existing = null;
  try {
    existing = await fsp.readFile(outFile, 'utf8');
  } catch {
    // File does not exist yet
  }

  if (existing !== generatedSource) {
    await fsp.writeFile(outFile, generatedSource, 'utf8');
  }

  console.log(
    `[pack-zips] extension=${extBundle.fileCount} files (${extBundle.byteLength} B), figma-plugin=${figmaBundle.fileCount} files (${figmaBundle.byteLength} B) -> src/generated/bundles.ts`,
  );
}

main().catch((err) => {
  console.error('[pack-zips] Failed:', err);
  process.exit(1);
});
